/**
 * SmogShield Core Domain Types & Interfaces
 *
 * Provides strongly-typed definitions for atmospheric telemetry,
 * user household profiles, mitigation action plans, and API contracts.
 */

/**
 * Standard EPA / US AQI Category names.
 */
export type AqiCategory =
  | "Good"
  | "Moderate"
  | "Unhealthy for Sensitive Groups"
  | "Unhealthy"
  | "Very Unhealthy"
  | "Hazardous";

/**
 * Color tokens corresponding to AQI severity tiers.
 */
export type AqiColorToken =
  | "emerald"
  | "amber"
  | "orange"
  | "red"
  | "severe"
  | "hazardous";

/**
 * Geographic location and coordinate details for a city or station.
 */
export interface CityLocation {
  name: string;
  country: string;
  admin1?: string;
  latitude: number;
  longitude: number;
}

/**
 * Hourly atmospheric forecast snapshot.
 */
export interface HourlyPoint {
  time: string;
  hourLabel: string;
  pm25: number;
  usAqi: number;
}

/**
 * Complete real-time air quality report with forecast and inversion windows.
 */
export interface AirQualityReport {
  usAqi: number;
  pm25: number;
  pm10: number;
  no2: number;
  o3: number;
  category: AqiCategory;
  colorToken: AqiColorToken;
  safestWindow: string;
  peakSmogWindow: string;
  hourlyForecast: HourlyPoint[];
  updatedAt: string;
}

/**
 * Supported household resident vulnerabilities.
 */
export type HouseholdMemberType =
  | "infants_kids"
  | "elderly"
  | "asthma_respiratory"
  | "pregnant"
  | "outdoor_workers"
  | "pets"
  | "general_adults";

/**
 * Primary mode of daily commuting.
 */
export type CommuteMode =
  | "private_car"
  | "two_wheeler"
  | "public_transit"
  | "walk_cycle"
  | "work_from_home";

/**
 * Household structure and ventilation boundary layer type.
 */
export type HomeType =
  | "apartment_highrise"
  | "independent_house"
  | "dense_urban_flat";

/**
 * Primary indoor cooking fuel.
 */
export type CookingFuel =
  | "lpg_gas"
  | "electric_induction"
  | "biomass_solid";

/**
 * Full household parameters used to personalize mitigation advice.
 */
export interface HouseholdProfile {
  city: string;
  latitude: number;
  longitude: number;
  householdMembers: HouseholdMemberType[];
  commuteMode: CommuteMode;
  homeType: HomeType;
  hasAirPurifier: boolean;
  cookingFuel: CookingFuel;
}

/**
 * Individual mitigation routine or hack item.
 */
export interface ActionItem {
  id: string;
  title: string;
  timingOrFrequency: string;
  description: string;
  healthImpact: string;
  emissionImpact: string;
  estimatedCo2SavedKgPerWeek: number;
  estimatedPm25ExposureReductionPct: number;
  difficulty: "Easy" | "Medium" | "High";
}

/**
 * Structured action plan generated by Gemini or the deterministic fallback engine.
 */
export interface GeneratedActionPlan {
  severitySummary: string;
  winterSmogInsight: string;
  dailyRoutines: ActionItem[];
  indoorHacks: ActionItem[];
  sustainableAlternatives: ActionItem[];
  communityTip: string;
}

/**
 * Summary atmospheric snapshot passed to AI generation models.
 */
export interface AqiSnapshot {
  usAqi: number;
  pm25: number;
  pm10: number;
  no2: number;
  o3: number;
  category: string;
  safestWindow: string;
  peakSmogWindow: string;
}

/**
 * Chat consultation message structure.
 */
export interface ChatMessage {
  id: string;
  role: "user" | "assistant";
  content: string;
  timestamp: string;
}

/**
 * Supabase persisted household profile record.
 */
export interface SupabaseProfile {
  city: string;
  has_kids: boolean;
  has_seniors: boolean;
  has_respiratory_condition: boolean;
  has_hepa_purifier: boolean;
  commute_mode: CommuteMode;
}

/**
 * Supabase saved plan row stored in PostgreSQL.
 */
export interface SavedPlanRow {
  id: string;
  user_id: string;
  city: string;
  aqi_value: number;
  plan_json: GeneratedActionPlan;
  completed_actions: string[];
  created_at: string;
}
